"""Generate c/src/ac4_tables.c from the repository's banked numeric tables
(ac4/tables/ac4_huffman.json, ac4/tables/ac4_sfb_offsets.json).

    python3 c/tools/gen_tables.py > c/src/ac4_tables.c

The ASF spectral, scale factor and noise fill Huffman codebooks, the scale
factor band offsets for the transform lengths that occur at 48 kHz with a
1536-sample frame, the A-SPX and A-CPL Huffman codebooks, the 640-tap QMF
prototype (ac4/tables/ac4_qwin.json), the A-SPX noise table
(ac4/tables/ac4_aspx_noise.json) and the spectral noise fill's
RANDOM_NOISE_TABLE (ac4/tables/ac4_random_noise.json). The generated file is
committed, so building the C library needs no Python.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(HERE, "..", "..", "ac4", "tables")

BOOKS = ["ASF_HCB_%d" % i for i in range(1, 12)] + \
    ["ASF_HCB_SCALEFAC", "ASF_HCB_SNF"]
LENGTHS = (2048, 1920, 1536, 1024, 960, 768, 512, 480, 384, 256, 240, 192,
           128, 120, 96)
# A-SPX books: [ENV_LEVEL_15, ENV_LEVEL_30, ENV_BALANCE_15, ENV_BALANCE_30,
# NOISE_LEVEL, NOISE_BALANCE] x [F0, DF, DT]
ASPX = ["ASPX_HCB_%s_%s" % (k, h)
        for k in ("ENV_LEVEL_15", "ENV_LEVEL_30", "ENV_BALANCE_15",
                  "ENV_BALANCE_30", "NOISE_LEVEL", "NOISE_BALANCE")
        for h in ("F0", "DF", "DT")]
# metadata books: the DRC gains, the dialogue enhancement parameters
MISC = ["DRC_HCB", "DE_HCB_ABS_0", "DE_HCB_DIFF_0", "DE_HCB_ABS_1",
        "DE_HCB_DIFF_1"]
# A-CPL books: [ALPHA, BETA, BETA3, GAMMA] x [FINE, COARSE] x [F0, DF, DT]
ACPL = ["ACPL_HCB_%s_%s_%s" % (k, q, h)
        for k in ("ALPHA", "BETA", "BETA3", "GAMMA")
        for q in ("FINE", "COARSE")
        for h in ("F0", "DF", "DT")]


def arr(name, ctype, vals, out):
    out.append("const %s %s[%d] = {" % (ctype, name, len(vals)))
    for i in range(0, len(vals), 12):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
    out.append("};")


def main():
    huff = json.load(open(os.path.join(TAB, "ac4_huffman.json")))
    sfb = json.load(open(os.path.join(TAB, "ac4_sfb_offsets.json")))
    out = ["/* SPDX-License-Identifier: Apache-2.0 */",
           "/* GENERATED by c/tools/gen_tables.py from the JSON tables in ac4/tables."
           " Do not edit. */",
           '#include "ac4_tables.h"', ""]
    for b in BOOKS:
        lens, cws = huff[b + "_LEN"], huff[b + "_CW"]
        if len(lens) != len(cws):
            sys.exit("length mismatch in " + b)
        arr("AC4T_" + b + "_LEN", "uint8_t", lens, out)
        arr("AC4T_" + b + "_CW", "uint32_t",
            [c & ((1 << L) - 1) if L > 0 else 0 for L, c in zip(lens, cws)],
            out)
        out.append("")
    for b in ASPX + ACPL + MISC:
        lens, cws = huff[b + "_LEN"], huff[b + "_CW"]
        if len(lens) != len(cws):
            sys.exit("length mismatch in " + b)
        arr("AC4T_" + b + "_LEN", "uint8_t", lens, out)
        arr("AC4T_" + b + "_CW", "uint32_t",
            [c & ((1 << L) - 1) if L > 0 else 0 for L, c in zip(lens, cws)],
            out)
        out.append("")
    for name, books in (("AC4T_BOOKS[AC4T_N_BOOKS]", BOOKS),
                        ("AC4T_ASPX_BOOKS[AC4T_N_ASPX_BOOKS]", ASPX),
                        ("AC4T_ACPL_BOOKS[AC4T_N_ACPL_BOOKS]", ACPL),
                        ("AC4T_MISC_BOOKS[AC4T_N_MISC_BOOKS]", MISC)):
        out.append("const ac4t_book %s = {" % name)
        for b in books:
            out.append("    { AC4T_%s_LEN, AC4T_%s_CW, %d }," % (
                b, b, len(huff[b + "_LEN"])))
        out.append("};")
        out.append("")
    qw = json.load(open(os.path.join(TAB, "ac4_qwin.json")))["coef"]
    nz = json.load(open(os.path.join(TAB, "ac4_aspx_noise.json")))
    if len(qw) != 640 or len(nz["re"]) != 512 or len(nz["im"]) != 512:
        sys.exit("QWIN / ASPX_NOISE sizes")
    out.append("const double AC4T_QWIN[640] = {")
    for i in range(0, 640, 4):
        out.append("    " + ", ".join(repr(float(v)) for v in qw[i:i + 4]) + ",")
    out.append("};")
    out.append("")
    out.append("const double AC4T_ASPX_NOISE[512][2] = {")
    for r, m in zip(nz["re"], nz["im"]):
        out.append("    { %r, %r }," % (float(r), float(m)))
    out.append("};")
    out.append("")
    rn = json.load(open(os.path.join(TAB, "ac4_random_noise.json")))["values"]
    if len(rn) != 256:
        sys.exit("RANDOM_NOISE_TABLE size")
    out.append("const float AC4T_RANDOM_NOISE[256] = {")
    for i in range(0, 256, 8):
        out.append("    " + ", ".join("%rf" % float(v) for v in rn[i:i + 8])
                   + ",")
    out.append("};")
    out.append("")
    for L in LENGTHS:
        off = sfb[str(L)]
        if off[-1] != L or any(off[i] >= off[i + 1]
                               for i in range(len(off) - 1)):
            sys.exit("band layout %d failed its gate" % L)
        arr("AC4T_SFB_%d" % L, "int16_t", off, out)
    out.append("")
    out.append("const ac4t_sfb AC4T_SFB[AC4T_N_SFB] = {")
    for L in LENGTHS:
        out.append("    { %d, AC4T_SFB_%d, %d }," % (L, L, len(sfb[str(L)]) - 1))
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
