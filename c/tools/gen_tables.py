"""Generate c/src/ac4_tables.c from the repository's banked numeric tables
(ac4/tables/ac4_huffman.json, ac4/tables/ac4_sfb_offsets.json).

    python3 c/tools/gen_tables.py > c/src/ac4_tables.c

Only the tables milestone 1 needs: the ASF spectral, scale factor and noise
fill Huffman codebooks, and the scale factor band offsets for the transform
lengths that occur at 48 kHz with a 1536-sample frame. The generated file is
committed, so building the C library needs no Python.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(HERE, "..", "..", "ac4", "tables")

BOOKS = ["ASF_HCB_%d" % i for i in range(1, 12)] + \
    ["ASF_HCB_SCALEFAC", "ASF_HCB_SNF"]
LENGTHS = (1536, 768, 384, 192, 96)


def arr(name, ctype, vals, out):
    out.append("const %s %s[%d] = {" % (ctype, name, len(vals)))
    for i in range(0, len(vals), 12):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
    out.append("};")


def main():
    huff = json.load(open(os.path.join(TAB, "ac4_huffman.json")))
    sfb = json.load(open(os.path.join(TAB, "ac4_sfb_offsets.json")))
    out = ["/* SPDX-License-Identifier: Apache-2.0 */",
           "/* GENERATED by c/tools/gen_tables.py from the JSON tables in ac4/tables."
           " Do not edit. */",
           '#include "ac4_tables.h"', ""]
    for b in BOOKS:
        lens, cws = huff[b + "_LEN"], huff[b + "_CW"]
        if len(lens) != len(cws):
            sys.exit("length mismatch in " + b)
        arr("AC4T_" + b + "_LEN", "uint8_t", lens, out)
        arr("AC4T_" + b + "_CW", "uint32_t",
            [c & ((1 << L) - 1) if L > 0 else 0 for L, c in zip(lens, cws)],
            out)
        out.append("")
    out.append("const ac4t_book AC4T_BOOKS[AC4T_N_BOOKS] = {")
    for b in BOOKS:
        out.append("    { AC4T_%s_LEN, AC4T_%s_CW, %d }," % (b, b,
                                                       len(huff[b + "_LEN"])))
    out.append("};")
    out.append("")
    for L in LENGTHS:
        off = sfb[str(L)]
        if off[-1] != L or any(off[i] >= off[i + 1]
                               for i in range(len(off) - 1)):
            sys.exit("band layout %d failed its gate" % L)
        arr("AC4T_SFB_%d" % L, "int16_t", off, out)
    out.append("")
    out.append("const ac4t_sfb AC4T_SFB[AC4T_N_SFB] = {")
    for L in LENGTHS:
        out.append("    { %d, AC4T_SFB_%d, %d }," % (L, L, len(sfb[str(L)]) - 1))
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
