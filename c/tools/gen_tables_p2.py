"""Generate src/ac4_tables_p2.c from ac4/tables/ac4_huffman_p2.json: the
twelve A-JOC codebooks of TS 103 190-2 Annex A.1.1, and the ISF
matrices of Annex A.2.1 (ac4/tables/ac4_isf.json) for the decoder's
layouts.

    python3 c/tools/gen_tables_p2.py > c/src/ac4_tables_p2.c"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(HERE, "..", "..", "ac4", "tables")
# AC4T_AJOC_BOOKS order: 6 * dry_wet + 3 * coarse_fine + F0 / DF / DT
AJOC = ["AJOC_HCB_%s_%s_%s" % (d, q, h) for d in ("DRY", "WET")
        for q in ("COARSE", "FINE") for h in ("F0", "DF", "DT")]


def arr(name, ctype, vals, out):
    out.append("static const %s %s[%d] = {" % (ctype, name, len(vals)))
    for i in range(0, len(vals), 12):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
    out.append("};")


def main():
    huff = json.load(open(os.path.join(TAB, "ac4_huffman_p2.json")))
    out = ["/* SPDX-License-Identifier: Apache-2.0 */",
           "/* GENERATED by c/tools/gen_tables_p2.py from "
           "ac4/tables/ac4_huffman_p2.json. Do not edit. */",
           '#include "ac4_tables.h"', ""]
    for b in AJOC:
        lens, cws = huff[b + "_LEN"], huff[b + "_CW"]
        if len(lens) != len(cws):
            sys.exit("length mismatch in " + b)
        arr("AC4T_" + b + "_LEN", "uint8_t", lens, out)
        arr("AC4T_" + b + "_CW", "uint32_t",
            [c & ((1 << L) - 1) if L > 0 else 0 for L, c in zip(lens, cws)],
            out)
        out.append("")
    out.append("const ac4t_book AC4T_AJOC_BOOKS[AC4T_N_AJOC_BOOKS] = {")
    for b in AJOC:
        out.append("    { AC4T_%s_LEN, AC4T_%s_CW, %d }," % (
            b, b, len(huff[b + "_LEN"])))
    out.append("};")
    out.append("")
    isf = json.load(open(os.path.join(TAB, "ac4_isf.json")))
    names = ("SR3100", "SR5300", "SR7300", "SR9500", "SR7530", "SR15951")
    outs = ("2", "5", "502", "504", "7", "702", "704")
    for n in names:
        for o in outs:
            m = isf["%s_to_%s" % (n, o)]
            arr("AC4T_ISF_%s_%s" % (n, o), "double",
                [repr(v) for row in m for v in row], out)
    out.append("/* [isf_config][layout 1 .. 7 - 1]: rows the ISF objects, "
               "columns the speakers without the LFE */")
    out.append("const double *const AC4T_ISF[6][7] = {")
    for n in names:
        out.append("    { " + ", ".join("AC4T_ISF_%s_%s" % (n, o)
                                         for o in outs) + " },")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
